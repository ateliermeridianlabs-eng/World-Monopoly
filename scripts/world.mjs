// Tokyo-Yokohama, Shenzhen-Hong Kong...) with a fisheye that keeps directions from the lens centre, so a city
// north of another stays north of it. Outlines are simplified and fattened where a parcel needs room
// (Florida, Kyushu, Scotland, Primorye); recognisable shapes matter more than coastline detail.

