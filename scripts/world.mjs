// Japan) are drawn far larger than true scale, but each sits in the right part of the world and everything in
// it keeps its real relative position. A projection maps lon and lat separately with piecewise-linear knots
// ([degree, cell] pairs, extrapolated linearly), so north stays north and east stays east inside a region.
