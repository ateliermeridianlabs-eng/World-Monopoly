// Builds data/board.json (the full, explicit square list) from data/sections.json and data/rules.json.
// Run: npm run board
import { readFileSync, writeFileSync } from 'node:fs';

const sections = JSON.parse(readFileSync('data/sections.json', 'utf8')).sections;
const rules = JSON.parse(readFileSync('data/rules.json', 'utf8'));

// Inside every section: 8 cities (c0..c7, cheapest first), 4 utility meters, 1 World Event, 1 Disaster.
const SECTION_PATTERN = ['c0', 'c1', 'water', 'c2', 'event', 'c3', 'gas', 'c4', 'c5', 'electricity', 'disaster', 'c6', 'wifi', 'c7'];
// Squares in the gap after each section. The last gap runs back into New Year.
const GAPS = [
  ['airport', 'highway'], ['airport', 'tax'], ['airport', 'highway'], ['airport', 'tax'],
  ['airport', 'highway'], ['airport', 'tax'], ['airport', 'highway'], ['airport', 'tax'],
  ['highway'],
];

const squares = [{ type: 'newYear', id: 'new-year', name: 'New Year' }];
let airportNo = 0, highwayNo = 0, taxNo = 0;

sections.forEach((section, i) => {
  for (const slot of SECTION_PATTERN) {
    if (slot.startsWith('c')) {
      const city = section.cities[Number(slot.slice(1))];
      squares.push({ type: 'city', id: city.id, name: city.name, section: section.id, price: city.price, image: city.image });
    } else if (slot === 'event') {
      squares.push({ type: 'event', id: `event-${section.id}`, name: 'World Event', section: section.id });
    } else if (slot === 'disaster') {
      squares.push({ type: 'disaster', id: `disaster-${section.id}`, name: 'Disaster', section: section.id });
    } else {
      const kind = rules.utilities.kinds.find((k) => k.id === slot);
      squares.push({ type: 'utility', id: `${slot}-${section.id}`, name: `${section.name} ${kind.name}`, section: section.id, utility: slot, price: rules.utilities.price });
    }
  }
  for (const gap of GAPS[i]) {
    if (gap === 'airport') squares.push({ type: 'airport', id: `airport-${++airportNo}`, name: `Airport ${airportNo}`, price: rules.airports.price });
    if (gap === 'highway') squares.push({ type: 'highway', id: `highway-${++highwayNo}`, name: `Highway ${highwayNo}` });
    if (gap === 'tax') squares.push({ type: 'tax', id: `tax-${++taxNo}`, name: 'Tax Office' });
  }
});

squares.forEach((s, index) => {
  s.index = index;
  s.checkpoint = index % rules.salary.checkpointEvery === 0;
});

const ids = new Set(squares.map((s) => s.id));
if (ids.size !== squares.length) throw new Error('duplicate square id');
if (squares.length % rules.salary.checkpointEvery !== 0) throw new Error(`board size ${squares.length} is not a multiple of checkpointEvery`);

const ordered = squares.map(({ index, id, type, name, checkpoint, ...rest }) => ({ index, id, type, name, checkpoint, ...rest }));
writeFileSync('data/board.json', JSON.stringify({ _note: 'Generated by scripts/generate-board.mjs. Do not edit by hand.', size: ordered.length, squares: ordered }, null, 2) + '\n');
console.log(`board.json: ${ordered.length} squares`);
